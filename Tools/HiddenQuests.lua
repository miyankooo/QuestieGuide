-- Writes Hidden.lua: the QuestieDB quests the game never offers on WoW Forever, as Questie hides them on its Era rules.
-- Usage, from the repo root: lua Tools/HiddenQuests.lua <Questie folder> <QuestieDB folder> > Hidden.lua
-- Rerun it when Questie or QuestieDB changes. Only quest IDs are taken over, never Questie code.
local questieDir, questieDbDir = arg[1], arg[2]
if not (questieDir and questieDbDir) then
    io.stderr:write("Usage: lua Tools/HiddenQuests.lua <Questie folder> <QuestieDB folder>\n")
    os.exit(1)
end

local function read(path)
    local file = assert(io.open(path, "rb"))
    local text = file:read("*a")
    file:close()
    return text
end

-- Questie on Forever: Era rules, no season, no Hardcore.
local modules = {}
local function module(name)
    modules[name] = modules[name] or {}
    return modules[name]
end
QuestieLoader = { CreateModule = function(_, name) return module(name) end, ImportModule = function(_, name) return module(name) end }
Questie = { IsForever = true, IsClassic = true, IsEra = true }
local expansions = module("Expansions")
expansions.Era, expansions.Tbc, expansions.Wotlk, expansions.Cata, expansions.MoP = 1, 2, 3, 4, 5
expansions.Current = expansions.Era
module("ContentPhases").activePhases = {}
module("QuestieEvent").eventQuests = {}

local hidden = {}

-- The blacklist: duplicates, quests never in the game, world events. HIDE_ON_MAP entries fail Questie's IsDoable too.
dofile(questieDir .. "/Database/Corrections/QuestieQuestBlacklist.lua")
local blacklist = module("QuestieQuestBlacklist")
for questId, hide in pairs(blacklist:Load()) do
    if hide then hidden[questId] = true end
end

-- The Scourge Invasion runs only on Season of Discovery.
for questId in pairs(blacklist.InvasionQuests) do
    hidden[questId] = true
end

-- Holiday quests, which Questie shows only while their event runs. The guide has no event calendar, so they stay hidden.
for path in read(questieDir .. "/Questie_Forever.toc"):gmatch("(Database\\Corrections\\Holidays\\quests\\[%w_]+%.lua)") do
    dofile(questieDir .. "/" .. path:gsub("\\", "/"))
end
for _, entry in ipairs(module("QuestieEvent").eventQuests) do
    if not entry[7] then hidden[entry[2]] = true end
end

-- Only quests QuestieDB carries matter.
local known = {}
for questId in read(questieDbDir .. "/QuestieDB_Forever.toc"):gmatch("\n## X%-Quest%-(%d+)%-") do
    known[tonumber(questId)] = true
end
local ids = {}
for questId in pairs(hidden) do
    if known[questId] then ids[#ids + 1] = questId end
end
table.sort(ids)

local version = read(questieDir .. "/Questie_Forever.toc"):match("## Version: ([%w%.]+)")
local dbVersion = read(questieDbDir .. "/QuestieDB_Forever.toc"):match("## Version: ([%w%.]+)")
local lines, line = {}, "   "
for _, questId in ipairs(ids) do
    local item = " " .. questId .. ","
    if #line + #item > 120 then
        lines[#lines + 1] = line
        line = "   "
    end
    line = line .. item
end
lines[#lines + 1] = line

io.write(([[
local _, ns = ...

-- QuestieDB quests the game never offers on WoW Forever, as Questie %s hides them: duplicates, quests never in the
-- game, world event and holiday quests, and the Scourge Invasion. %d of QuestieDB %s's quests.
-- Generated by Tools/HiddenQuests.lua; rerun it when Questie or QuestieDB changes.
local IDS = {
%s
}

local hidden = {}
for _, questId in ipairs(IDS) do
    hidden[questId] = true
end
ns.HIDDEN_QUESTS = hidden
]]):format(version, #ids, dbVersion, table.concat(lines, "\n")))
